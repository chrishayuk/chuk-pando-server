#!/usr/bin/env python3
"""Generate THIRD-PARTY-LICENSES.txt: every crate compiled into `pando` (normal and build dependencies, all
targets, so it covers all five release platforms), its declared licence, and the full text of every licence and
notice file the crate ships. It fails (exit 1) if a crate's licence is not on the allow-list, or if a crate ships
no licence text at all, so a missing notice cannot reach a release (docs/PROVENANCE-REVIEW.md, Q5).

Usage: third_party_licenses.py [--check FILE]   (writes to stdout; --check compares with FILE and fails on drift)
Needs: cargo, with the dependencies fetched (CARGO_HOME as for the build)."""
import json, os, re, subprocess, sys

SERVER = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "server")
# SPDX identifiers whose terms permit redistribution in an Apache-2.0 binary with the notices below
ALLOWED = {"MIT", "Apache-2.0", "ISC", "BSD-3-Clause", "Zlib", "0BSD", "Unlicense", "Unicode-3.0", "CDLA-Permissive-2.0",
           "Apache-2.0 WITH LLVM-exception"}
LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|COPYRIGHT|UNLICENSE)([-_.].*)?$", re.I)


def ids(expr):
    return [t.strip() for t in re.split(r"\bOR\b|\bAND\b|[()/]", expr.replace("WITH LLVM-exception", "WITH_LLVM")) if t.strip()]


def acceptable(expr):
    # every alternative of an OR needs only one acceptable member; AND needs all. Conservative: require every id
    # mentioned to be allowed, except members of an OR group when another member is allowed.
    norm = expr.replace("WITH LLVM-exception", "WITH_LLVM")
    for conj in re.split(r"\bAND\b", norm.replace("(", "").replace(")", "")):
        alts = [a.strip().replace("WITH_LLVM", "WITH LLVM-exception") for a in re.split(r"\bOR\b|/", conj) if a.strip()]
        if not any(a in ALLOWED for a in alts):
            return False
    return True


def main():
    # every crate's sources must be present for its licence files: fetch them for all targets (no-op if cached)
    subprocess.run(["cargo", "fetch", "--locked"], cwd=SERVER, check=False, capture_output=True)
    meta = json.loads(subprocess.check_output(["cargo", "metadata", "--locked", "--format-version", "1"], cwd=SERVER))
    pk = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    seen, st = set(), [root]
    while st:
        i = st.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            if any(k["kind"] in (None, "build") for k in d["dep_kinds"]):
                st.append(d["pkg"])
    seen.discard(root)
    out, bad = [], []
    crates = sorted((pk[i] for i in seen), key=lambda p: (p["name"], p["version"]))
    out.append("Third-party software compiled into pando\n" + "=" * 41 + "\n")
    out.append("pando is licensed under the Apache License 2.0 (LICENSE). It is built with the following crates, each\n"
               "under its own licence, reproduced in full below as shipped by the crate. Generated by\n"
               "verify/release/third_party_licenses.py from Cargo.lock; covers every release platform.\n")
    for p in crates:
        out.append(f"  {p['name']} {p['version']}  ({p['license']})")
    for p in crates:
        lic = p.get("license") or ""
        if not lic or not acceptable(lic):
            bad.append(f"{p['name']} {p['version']}: licence {lic!r} not on the allow-list")
        d = os.path.dirname(p["manifest_path"])
        files = sorted(f for f in os.listdir(d) if LICENSE_FILE.match(f) and os.path.isfile(os.path.join(d, f)))
        if p.get("license_file"):
            files = sorted(set(files) | {os.path.relpath(os.path.join(d, p["license_file"]), d)})
        if not files:
            bad.append(f"{p['name']} {p['version']}: no licence text shipped in the crate")
        out.append("\n" + "-" * 100 + f"\n{p['name']} {p['version']}  ({lic})\n" + (p.get("repository") or "") + "\n")
        for f in files:
            txt = open(os.path.join(d, f), encoding="utf-8", errors="replace").read().replace("\r\n", "\n").rstrip()
            out.append(f"--- {f} ---\n{txt}\n")
    text = "\n".join(out) + "\n"
    if bad:
        print("\n".join(bad), file=sys.stderr)
        sys.exit(1)
    if len(sys.argv) == 3 and sys.argv[1] == "--check":
        if open(sys.argv[2], encoding="utf-8").read() != text:
            print(f"{sys.argv[2]} is out of date: regenerate it with {sys.argv[0]}", file=sys.stderr)
            sys.exit(1)
        print(f"{sys.argv[2]}: up to date ({len(crates)} crates)", file=sys.stderr)
        return
    sys.stdout.write(text)
    print(f"{len(crates)} crates", file=sys.stderr)


if __name__ == "__main__":
    main()
